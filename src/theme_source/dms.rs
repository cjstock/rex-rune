//! Set up DMS: the theme source template, and the DMS drop-in that has DMS fill it in.
//!
//! DMS runs matugen whenever it regenerates the desktop's colours (a new wallpaper, light or
//! dark), and appends every `matugen/dms/configs/*.toml` under the user's config folder to that
//! run. [`set_up`] writes two files this client owns, each starting with [`HEADER`]:
//!
//! - the template, [`TEMPLATE`], at `$XDG_DATA_HOME/rex-rune/matugen/theme-source-template`;
//! - the drop-in, `$XDG_CONFIG_HOME/matugen/dms/configs/rex-rune.toml`, whose one
//!   `[templates.rex-rune]` renders the template into the theme source.
//!
//! The user's own `matugen/config.toml` is never read or written, and nothing here runs DMS
//! or matugen. Paths in the drop-in are `~/…` under home and absolute otherwise, never
//! relative: DMS merges its configs in a temporary folder, and matugen resolves a relative
//! path against that.
use super::FILE_NAME;
use crate::platform::{dirs, tools::Search};
use std::{
    io,
    path::{Path, PathBuf},
};

/// The theme source template: DMS's own Ghostty template's terminal keys, Material roles for
/// the chrome, dank16 for its status colours, all of the current mode (`.default.`), and no
/// per-template `type`, which would make matugen drop DMS's colours.
pub const TEMPLATE: &str = include_str!("../../resources/matugen/theme-source-template");

/// How every file this client writes for DMS starts, and how it knows them for its own.
pub const HEADER: &str = "# Generated by Rex Rune";

/// The drop-in's table, a name no other template uses.
const TABLE: &str = "templates.rex-rune";

/// Where Set up DMS reads and writes, and where it looks for `dms`.
#[derive(Clone, Debug)]
pub struct Places {
    pub home: PathBuf,
    /// `$XDG_DATA_HOME`, else `~/.local/share`.
    pub data: PathBuf,
    /// `$XDG_CONFIG_HOME`, else `~/.config`.
    pub config: PathBuf,
    /// This client's state folder, where the theme source is by default.
    pub state: PathBuf,
    pub tools: Search,
}

impl Places {
    /// The places this process's environment names.
    pub fn from_env() -> Self {
        Self {
            home: dirs::home(),
            data: dirs::xdg_data(),
            config: dirs::xdg_config(),
            state: dirs::state(),
            tools: Search::from_env(),
        }
    }

    /// Where the theme source is read from: `setting` (absolute, or starting with `~`) when
    /// given, else `theme-source` in the state folder.
    pub fn theme_source(&self, setting: Option<&str>) -> PathBuf {
        match setting.map(str::trim).filter(|path| !path.is_empty()) {
            Some(path) => match path.strip_prefix('~') {
                Some("") => self.home.clone(),
                Some(rest) if rest.starts_with('/') => self.home.join(rest.trim_start_matches('/')),
                _ => PathBuf::from(path),
            },
            None => self.state.join(FILE_NAME),
        }
    }

    /// The template's file.
    pub fn template(&self) -> PathBuf {
        self.data
            .join(dirs::APP)
            .join("matugen/theme-source-template")
    }

    /// The DMS drop-in's file.
    pub fn drop_in(&self) -> PathBuf {
        self.config.join("matugen/dms/configs/rex-rune.toml")
    }

    /// Whether DMS is installed.
    pub fn dms(&self) -> bool {
        self.tools.finds("dms")
    }
}

/// The drop-in this client writes for a theme source at `theme_source`, or why it can't.
pub fn drop_in_text(places: &Places, theme_source: &Path) -> Result<String, String> {
    Ok(format!(
        "{HEADER} when Set up DMS was pressed. DMS adds it to every colour change, so\n\
         # that it writes the theme source Rex Rune follows. Delete this file to stop.\n\
         [{TABLE}]\n\
         input_path = {}\n\
         output_path = {}\n",
        toml_string(&from_home(&places.template(), &places.home)?),
        toml_string(&from_home(theme_source, &places.home)?),
    ))
}

/// What the drop-in at its place is, for a theme source at `theme_source`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DropIn {
    Missing,
    /// What this client would write.
    Current,
    /// This client's, but it has DMS write the theme source to another file.
    WritesElsewhere(PathBuf),
    /// This client's, and otherwise not what it writes now.
    Stale,
    /// A file of that name this client didn't write; left alone.
    Foreign,
}

/// Read the drop-in back and say what it is.
pub fn drop_in(places: &Places, theme_source: &Path) -> DropIn {
    let Ok(text) = std::fs::read_to_string(places.drop_in()) else {
        return if places.drop_in().exists() {
            DropIn::Foreign
        } else {
            DropIn::Missing
        };
    };
    if !text.starts_with(HEADER) {
        return DropIn::Foreign;
    }
    if drop_in_text(places, theme_source).is_ok_and(|wanted| wanted == text) {
        return DropIn::Current;
    }
    match output_path(&text).map(|path| places.theme_source(Some(&path))) {
        Some(path) if path != theme_source => DropIn::WritesElsewhere(path),
        _ => DropIn::Stale,
    }
}

/// Write the template and then the drop-in, so the drop-in never names a template that isn't
/// there. `own_folder`: the theme source is in this client's state folder, made here so DMS
/// can write into it; a folder the person chose is theirs to make.
pub fn set_up(places: &Places, theme_source: &Path, own_folder: bool) -> io::Result<()> {
    let drop_in = drop_in_text(places, theme_source).map_err(io::Error::other)?;
    write(&places.template(), TEMPLATE)?;
    if own_folder && let Some(parent) = theme_source.parent() {
        std::fs::create_dir_all(parent)?;
    }
    write(&places.drop_in(), &drop_in)
}

/// At launch: rewrite the template when this client wrote it and its text is not this
/// version's. Whether it was rewritten. The drop-in is only ever written by [`set_up`].
pub fn refresh_template(places: &Places) -> io::Result<bool> {
    let path = places.template();
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(false),
        Err(error) => return Err(error),
    };
    if !text.starts_with(HEADER) || text == TEMPLATE {
        return Ok(false);
    }
    write(&path, TEMPLATE).map(|()| true)
}

/// Write `text` in place, as matugen writes its own outputs, making the folder first.
fn write(path: &Path, text: &str) -> io::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, text)
}

/// `path` as the drop-in names it: `~/…` under home, absolute otherwise.
fn from_home(path: &Path, home: &Path) -> Result<String, String> {
    if !path.is_absolute() {
        return Err(format!("{} is not an absolute path", path.display()));
    }
    let text = |path: &Path| {
        path.to_str()
            .map(str::to_owned)
            .ok_or_else(|| format!("{} is not UTF-8", path.display()))
    };
    match path.strip_prefix(home) {
        Ok(rest) if home.is_absolute() && home.components().count() > 1 => {
            Ok(format!("~/{}", text(rest)?))
        }
        _ => text(path),
    }
}

/// A TOML string holding `value`: a literal string when it can be one, as DMS's own configs
/// are written, else a basic string with escapes.
fn toml_string(value: &str) -> String {
    if !value.contains('\'') && !value.chars().any(char::is_control) {
        return format!("'{value}'");
    }
    let mut out = String::from("\"");
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The `output_path` of the drop-in's table, as written.
fn output_path(text: &str) -> Option<String> {
    let mut in_table = false;
    for line in text.lines().map(str::trim) {
        if line.starts_with('[') {
            in_table = line == format!("[{TABLE}]");
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        if in_table && key.trim() == "output_path" {
            return toml_value(value.trim());
        }
    }
    None
}

/// A TOML string's value, as [`toml_string`] writes them.
fn toml_value(text: &str) -> Option<String> {
    if let Some(rest) = text.strip_prefix('\'') {
        return rest.split_once('\'').map(|(value, _)| value.to_owned());
    }
    let mut chars = text.strip_prefix('"')?.chars();
    let mut out = String::new();
    while let Some(c) = chars.next() {
        match c {
            '"' => return Some(out),
            '\\' => match chars.next()? {
                'u' => {
                    let code: String = chars.by_ref().take(4).collect();
                    out.push(char::from_u32(u32::from_str_radix(&code, 16).ok()?)?);
                }
                'n' => out.push('\n'),
                't' => out.push('\t'),
                other => out.push(other),
            },
            c => out.push(c),
        }
    }
    None
}

