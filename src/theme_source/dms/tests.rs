use super::*;
use crate::download::tests::Temp;

/// The folders of a private home under `temp`, with a fake `dms` when `dms` is true. The
/// fake is never run: finding it is all a lookup does.
fn places(temp: &Temp, dms: bool) -> Places {
    let home = temp.0.join("home");
    let bin = temp.dir("bin");
    if dms {
        std::fs::write(bin.join("dms"), "#!/bin/sh\n# a test's fake dms\nexit 1\n").unwrap();
    }
    Places {
        data: home.join(".local/share"),
        config: home.join(".config"),
        state: home.join(".local/state/rex-rune"),
        tools: Search {
            path: Some(bin.into_os_string()),
            user_bin: home.join(".local/bin"),
        },
        home,
    }
}

#[test]
fn the_template_is_pinned() {
    let palette: String = (0..16)
        .map(|n| format!("palette = {n}={{{{dank16term.color{n}.default.hex}}}}\n"))
        .collect();
    let expected = format!(
        "\
# Generated by Rex Rune from its theme source template; DMS fills in the colours.
# Edits here are lost: Rex Rune rewrites the template, and DMS the theme source.
rex-rune-theme-source = 1
scheme = {{{{mode}}}}

background = {{{{colors.background.default.hex}}}}
foreground = {{{{colors.on_surface.default.hex}}}}
cursor-color = {{{{colors.primary.default.hex}}}}
selection-background = {{{{colors.primary_container.default.hex}}}}
selection-foreground = {{{{colors.on_surface.default.hex}}}}

{palette}
chrome-ground = {{{{colors.surface.default.hex}}}}
chrome-card = {{{{colors.surface.default.hex}}}}
chrome-popover = {{{{colors.surface_container_high.default.hex}}}}
chrome-ink = {{{{colors.on_surface.default.hex}}}}
chrome-muted = {{{{colors.on_surface_variant.default.hex}}}}
chrome-accent = {{{{colors.primary.default.hex}}}}
chrome-accent2 = {{{{colors.tertiary.default.hex}}}}
chrome-on-accent = {{{{colors.on_primary.default.hex}}}}
chrome-danger = {{{{dank16.color1.default.hex}}}}
chrome-live = {{{{dank16.color2.default.hex}}}}
chrome-warning = {{{{dank16.color3.default.hex}}}}
"
    );
    assert_eq!(TEMPLATE, expected);
    assert!(TEMPLATE.starts_with(HEADER));
    assert!(
        !TEMPLATE.contains(".dark.") && !TEMPLATE.contains(".light."),
        "the current mode's colours throughout"
    );
    assert!(!TEMPLATE.contains("type"), "no per-template type");
}

#[test]
fn the_files_live_under_the_users_data_and_config_folders() {
    let temp = Temp::new("dms-places");
    let p = places(&temp, false);
    let home = temp.0.join("home");
    assert_eq!(
        p.template(),
        home.join(".local/share/rex-rune/matugen/theme-source-template")
    );
    assert_eq!(
        p.drop_in(),
        home.join(".config/matugen/dms/configs/rex-rune.toml")
    );
    assert_eq!(
        p.theme_source(None),
        home.join(".local/state/rex-rune/theme-source")
    );
    assert_eq!(p.theme_source(Some("  ")), p.theme_source(None));
    assert_eq!(p.theme_source(Some("~/x/y")), home.join("x/y"));
    assert_eq!(p.theme_source(Some("/a/b")), Path::new("/a/b"));
}

#[test]
fn the_drop_in_names_both_files_from_home_when_they_are_under_it() {
    let temp = Temp::new("dms-drop-in");
    let p = places(&temp, false);
    assert_eq!(
        drop_in_text(&p, &p.theme_source(None)).unwrap(),
        "\
# Generated by Rex Rune when Set up DMS was pressed. DMS adds it to every colour change, so
# that it writes the theme source Rex Rune follows. Delete this file to stop.
[templates.rex-rune]
input_path = '~/.local/share/rex-rune/matugen/theme-source-template'
output_path = '~/.local/state/rex-rune/theme-source'
"
    );
    let text = drop_in_text(&p, Path::new("/srv/it's/theme")).unwrap();
    assert!(
        text.ends_with("output_path = \"/srv/it's/theme\"\n"),
        "absolute outside home, quoted so the TOML holds: {text}"
    );
    assert!(
        drop_in_text(&p, Path::new("relative/theme")).is_err(),
        "never relative: DMS merges its configs under /tmp"
    );
}

#[test]
fn setting_up_writes_both_files_and_reads_back_as_current() {
    let temp = Temp::new("dms-set-up");
    let p = places(&temp, true);
    let source = p.theme_source(None);
    assert!(p.dms());
    assert_eq!(drop_in(&p, &source), DropIn::Missing);
    set_up(&p, &source, true).unwrap();
    assert_eq!(std::fs::read_to_string(p.template()).unwrap(), TEMPLATE);
    assert_eq!(
        std::fs::read_to_string(p.drop_in()).unwrap(),
        drop_in_text(&p, &source).unwrap()
    );
    assert!(
        source.parent().unwrap().is_dir(),
        "the state folder DMS writes into"
    );
    assert_eq!(drop_in(&p, &source), DropIn::Current);
    assert!(!p.config.join("matugen/config.toml").exists());
}

#[test]
fn a_drop_in_for_another_path_says_where_dms_writes() {
    let temp = Temp::new("dms-elsewhere");
    let p = places(&temp, true);
    let before = p.theme_source(None);
    set_up(&p, &before, true).unwrap();
    let now = temp.0.join("elsewhere/theme");
    assert_eq!(drop_in(&p, &now), DropIn::WritesElsewhere(before.clone()));
    // Set up for a path the person chose: their folder is theirs to make.
    set_up(&p, &now, false).unwrap();
    assert_eq!(drop_in(&p, &now), DropIn::Current);
    assert!(!now.parent().unwrap().exists());

    // Ours, pointing at the same file, but otherwise not what this client writes.
    let text = std::fs::read_to_string(p.drop_in()).unwrap();
    std::fs::write(p.drop_in(), text.replace("theme-source-template", "old")).unwrap();
    assert_eq!(drop_in(&p, &now), DropIn::Stale);
    // Someone else's file of that name is left alone.
    std::fs::write(p.drop_in(), "[templates.rex-rune]\n").unwrap();
    assert_eq!(drop_in(&p, &now), DropIn::Foreign);
}

#[test]
fn launch_refreshes_only_a_template_this_client_wrote() {
    let temp = Temp::new("dms-refresh");
    let p = places(&temp, false);
    assert!(
        !refresh_template(&p).unwrap(),
        "nothing there: nothing written"
    );
    assert!(!p.template().exists());
    std::fs::create_dir_all(p.template().parent().unwrap()).unwrap();
    let older = format!("{HEADER} long ago\nbackground = {{{{colors.background.default.hex}}}}\n");
    std::fs::write(p.template(), &older).unwrap();
    assert!(refresh_template(&p).unwrap());
    assert_eq!(std::fs::read_to_string(p.template()).unwrap(), TEMPLATE);
    assert!(!refresh_template(&p).unwrap(), "already current");
    std::fs::write(p.template(), "my own template\n").unwrap();
    assert!(
        !refresh_template(&p).unwrap(),
        "without the header it isn't ours"
    );
    assert_eq!(
        std::fs::read_to_string(p.template()).unwrap(),
        "my own template\n"
    );
}

#[test]
fn dms_is_found_only_where_the_lookup_looks() {
    let temp = Temp::new("dms-lookup");
    assert!(!places(&temp, false).dms());
    assert!(places(&temp, true).dms());
}
